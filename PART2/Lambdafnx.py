# Lambda functions are the short , one liner functions that are used to perform simple tasks
# they are created using lambda keyword
# these functions are anonymous and do not have a name like regular functions defined with def

# its basic syntax looks like = > 
# lambda arguments: expression
# arguments -> 1 or more parameters
# expression -> single expression whose result is automatically returned

# example of lambda function
square = lambda x: x*x
print(square(5))